"""Generate zprof_trace_defaults.h from Zephyr's tracing.h.

With CONFIG_TRACING_CUSTOM, Zephyr's tracing.h includes "zephyr_custom_tracing.h"
instead of its own block of empty hooks, so a custom format must define every
hook the kernel, drivers and subsystems call (about 360 at v4.4.0). zprof
defines the ones it records; this script copies every other hook from the
default block of the pinned tracing.h, each one wrapped in #ifndef so the
definitions made before it win. A hook added by a later Zephyr is then empty
in zprof builds until zprof records it, instead of breaking the build.

  gen_trace_defaults.py <zephyr>/include/zephyr/tracing/tracing.h <out.h> [--list]

--list prints the hook names, one per line (for the test that compares the
hook list with the pinned tree).
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

START = re.compile(r"^#elif\s+defined\s*\(?\s*CONFIG_TRACING_CUSTOM\b")
DEFINE = re.compile(r"^#define\s+(sys_(?:port_)?trace_\w+)(\([^)]*\))?(.*)$")


def hooks(text: str) -> list[tuple[str, str, str]]:
    """(name, params, body) of every #define in the default block of tracing.h."""
    lines = text.splitlines()
    try:
        at = next(i for i, ln in enumerate(lines) if START.match(ln.strip()))
    except StopIteration:
        raise SystemExit("tracing.h: no '#elif defined CONFIG_TRACING_CUSTOM' (has the format choice changed?)")
    # the default block is the #else that follows the CUSTOM branch
    at = next(i for i in range(at + 1, len(lines)) if lines[i].strip().startswith("#else"))
    out, i = [], at + 1
    while i < len(lines):
        ln = lines[i].rstrip()
        while ln.endswith("\\") and i + 1 < len(lines):  # continuation lines
            i += 1
            ln = ln[:-1].rstrip() + " " + lines[i].strip()
        m = DEFINE.match(ln.strip())
        if m:
            out.append((m.group(1), m.group(2) or "", m.group(3).strip()))
        i += 1
    if len(out) < 100:
        raise SystemExit(f"tracing.h: only {len(out)} hooks found in the default block; refusing")
    return out


def main() -> None:
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    text = src.read_text(encoding="utf-8")
    found = hooks(text)
    if "--list" in sys.argv:
        for name, _, _ in found:
            print(name)
        return
    digest = hashlib.sha256(text.encode()).hexdigest()[:16]
    body = [
        "/* Generated by zprof scripts/gen_trace_defaults.py: do not edit. */",
        f"/* From {src.as_posix()} (sha256 {digest}...), {len(found)} hooks. */",
        "#ifndef ZPROF_TRACE_DEFAULTS_H_",
        "#define ZPROF_TRACE_DEFAULTS_H_",
        "",
    ]
    for name, params, mbody in found:
        body += [f"#ifndef {name}", f"#define {name}{params}{(' ' + mbody) if mbody else ''}", "#endif"]
    body += ["", "#endif /* ZPROF_TRACE_DEFAULTS_H_ */", ""]
    new = "\n".join(body)
    dst.parent.mkdir(parents=True, exist_ok=True)
    if not dst.exists() or dst.read_text(encoding="utf-8") != new:  # keep the mtime when unchanged
        dst.write_text(new, encoding="utf-8")


if __name__ == "__main__":
    main()
