"""Write zprof_build_id.c: 16 random bytes that identify this build.

Zephyr links with --build-id=none, so the image carries no build id of its
own. zprof sends these bytes in its hello; the bridge reads the bytes of the
symbol zprof_build_id from the ELF it was given and refuses an ELF that does
not match (its names would be wrong). Run on every build.

  gen_build_id.py <out.c>
"""
import sys
import uuid
from pathlib import Path

out = Path(sys.argv[1])
b = uuid.uuid4().bytes
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "/* Generated by zprof scripts/gen_build_id.py on every build: do not edit. */\n"
    "#include <stdint.h>\n"
    "__attribute__((used)) const uint8_t zprof_build_id[16] = {"
    + ", ".join(f"0x{x:02x}" for x in b)
    + "};\n",
    encoding="ascii",
)
